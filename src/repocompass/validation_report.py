"""Write the cutoff validation results: one JSON file per repository and a Markdown summary.

The Markdown is generated from the same numbers as the JSON, so nothing is copied by hand.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from repocompass.metrics import NOT_ENOUGH_DATA
from repocompass.validation import RepoCheck, to_json

__all__ = ["RESAMPLES", "SEED", "write_results"]

RESAMPLES = 10_000
SEED = 0
DAYS_PER_MONTH = 30.44
FEW_AREAS = 5  # below this, the summary says the bootstrap interval says little
MISSING = "-"


def _num(value: float | None) -> str:
    return MISSING if value is None else f"{value:.3f}"


def _interval(value: tuple[float, float] | None) -> str:
    return MISSING if value is None else f"[{value[0]:.3f}, {value[1]:.3f}]"


def _repo_section(check: RepoCheck, min_sample: int, cap: int) -> list[str]:
    banded = [a for a in check.areas if a.band_before != NOT_ENOUGH_DATA]
    qualifying = [a for a in banded if a.qualifies]
    lines = [
        f"### {check.slug}",
        "",
        f"Snapshot {check.snapshot.date()}, cutoff {check.cutoff.date()}. "
        f"Before: {check.n_before} mature newcomer PRs, repo rate {_num(check.repo_rate_before)}. "
        f"After: {check.n_after} mature newcomer PRs, repo rate {_num(check.repo_rate_after)}.",
        "",
        f"{len(banded)} area{'' if len(banded) == 1 else 's'} had at least {min_sample} "
        "mature newcomer PRs before the cutoff; "
        f"{len(qualifying)} of them also had at least {min_sample} after it.",
        "",
        (
            f"Sampled: these months were capped at {cap} human PRs: "
            f"{', '.join(check.capped_months)}."
            if check.capped_months
            else "Not sampled: no month of the stored analysis was capped."
        ),
        "",
        f"Newcomer-status check: at most {check.possible_newcomer_leaks} before-cutoff PRs are "
        "stored as non-newcomer with no earlier PR by the same author in the stored window "
        "that merged before the cutoff (an upper bound on PRs misclassified with later "
        "information).",
        "",
    ]
    if qualifying:
        lines += [
            "| area | band before | n before | rate before [95% interval] "
            "| n after | rate after | held |",
            "|---|---|---|---|---|---|---|",
        ]
        for a in qualifying:
            held = MISSING if a.held is None else ("yes" if a.held else "no")
            lines.append(
                f"| `{a.area}` | {a.band_before} | {a.n_before} "
                f"| {a.merged_before / a.n_before:.3f} {_interval(a.wilson_before)} "
                f"| {a.n_after} | {_num(a.rate_after)} | {held} |"
            )
        lines.append("")
    return lines


def _same_outcome(n: int) -> str:
    who = {1: "There is only one qualifying area", 2: "Both qualifying areas had the same outcome"}
    start = who.get(n, f"All {n} qualifying areas had the same outcome")
    return (
        f"{start}, so every resample is the same and the interval is degenerate: "
        "it carries no information."
    )


def _pooled_section(pooled: dict[str, Any]) -> list[str]:
    lines = ["## Pooled across repositories", ""]
    for key, label in (("above", "above repo average"), ("below", "below repo average")):
        p = pooled[key]
        if p["areas"] == 0:
            lines.append(f"- **{label}**: no area qualified in both periods; not computable.")
        else:
            lines.append(
                f"- **{label}**: {p['held']} of {p['areas']} qualifying areas held "
                f"(proportion {_num(p['proportion'])}, "
                f"bootstrap 95% CI {_interval(p['bootstrap_95'])})."
            )
            if p["held"] in (0, p["areas"]):
                lines.append(f"  {_same_outcome(p['areas'])}")
            elif p["areas"] < FEW_AREAS:
                lines.append(
                    f"  With only {p['areas']} areas, the bootstrap interval carries little "
                    "information."
                )
    flat = pooled["no_clear_difference_above_after"]
    lines.append(
        f"- For comparison, **no clear difference** areas: {flat['above']} of {flat['areas']} "
        "had an after rate above the after repo rate."
    )
    return [*lines, ""]


def _method(cutoff_days: int, params: dict[str, Any], command: str) -> list[str]:
    maturity, minimum, window = params["maturity_days"], params["min_sample"], params["window_days"]
    # PRs need maturity_days to count, so each period loses that much at its end
    before_months = (window - cutoff_days - maturity) / DAYS_PER_MONTH
    after_months = (cutoff_days - maturity) / DAYS_PER_MONTH
    return [
        "# Cutoff validation",
        "",
        f"Generated by `{command}`. All values are measured from the stored analyses.",
        "",
        "## Method (fixed before running)",
        "",
        f"- Window: each analysis covers {window} days ({window / DAYS_PER_MONTH:.0f} months) "
        f"of PRs. Cutoff: {cutoff_days} days before each repository's snapshot.",
        f"- Before sample: newcomer PRs created at least {maturity} days before the cutoff and "
        "merged or closed by the cutoff, judged from `merged_at` / `closed_at` rather than from "
        "their state today.",
        f"- After sample: newcomer PRs created on or after the cutoff and at least {maturity} days "
        "before the snapshot, merged or closed by the snapshot.",
        "- Bands are made on the before sample exactly as in a report: the 95% Wilson interval "
        "of an area's merge rate against the before repo rate.",
        "- An area **held** if its after merge rate was on the same side of the after repo rate "
        '(above for "above repo average", below for "below repo average").',
        f"- Only areas with at least {minimum} mature newcomer PRs in both periods count.",
        f"- Bootstrap: {RESAMPLES:,} resamples of the qualifying areas, seed {SEED}, "
        "percentile interval.",
        "",
        "## Limitations",
        "",
        "- Newcomer status comes from the stored analysis, which used merges up to the snapshot, "
        "so some before-cutoff PRs may be classified with information from after the cutoff "
        "(each repository below gives an upper bound).",
        "- Only the last close or merge time of a PR is stored: a PR closed before the cutoff "
        "and reopened after it looks open at the cutoff and drops out of the before sample.",
        "- The bootstrap treats areas as independent, though areas of one repository share "
        "tied PRs and are compared with a repo rate that includes their own PRs.",
        "- Areas are those of the tree at the snapshot; PRs keep the area they were assigned then.",
        f"- The before period holds about {before_months:.0f} months of PRs and the after period "
        f"about {after_months:.0f}, so areas can fall below the minimum sample in one of them. "
        "One cutoff per repository.",
        "- A sampled analysis (any month capped) validates the sample, not every PR.",
        "",
    ]


def write_results(
    checks: list[RepoCheck],
    pooled: dict[str, Any],
    params: dict[str, Any],
    cutoff_days: int,
    out_dir: Path,
    command: str,
) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    for check in checks:
        name = check.slug.replace("/", "__") + ".json"
        (out_dir / name).write_text(json.dumps(to_json(check), indent=2), encoding="utf-8")
    lines = [*_method(cutoff_days, params, command), "## Per repository", ""]
    for check in checks:
        lines += _repo_section(check, params["min_sample"], params["monthly_sample_cap"])
    lines += _pooled_section(pooled)
    summary = out_dir / "summary.md"
    summary.write_text("\n".join(lines), encoding="utf-8")
    (out_dir / "pooled.json").write_text(json.dumps(pooled, indent=2), encoding="utf-8")
    return summary
